#!/usr/bin/env bash
# Capture everything the report needs about the experiment image, on the machine
# that actually has Docker. Output is a markdown block that can be pasted
# straight into docs/environment.md (section L2).
#
# Usage (on a machine with Docker, inside the repository):
#   ./docker/verify.sh            # builds go1.22 + go1.21, then measures
#   ./docker/verify.sh --quick    # only go1.22 (skips the extension image)
#   ./docker/verify.sh --no-build # measure existing images only
#
# Everything printed is measured on the spot. Nothing is guessed: if a step
# fails, it prints "FAILED: <cmd>" and the block says so, so nobody can paste an
# environment number that was never produced.
set -uo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$REPO_ROOT" || exit 1

BASE22="golang:1.22.4-bookworm@sha256:0c02666907338370a3272af1b4642a184968911d2317f0bd010dcef89a081d6f"
BASE21="golang:1.21.13-bookworm@sha256:c6a5b9308b3f3095e8fde83c8bf4d68bd101fce606c1a0a1394522542509dda9"
TAG22="cs340-repro:go1.22"
TAG21="cs340-repro:go1.21"
MODE="full"
BUILD=1

for arg in "$@"; do
  case "$arg" in
    --quick) MODE="quick" ;;
    --no-build) BUILD=0 ;;
    -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
    *) echo "unknown option: $arg" >&2; exit 2 ;;
  esac
done

fail() { echo "- $1: **FAILED** ($2)"; }
ok()   { echo "- $1: \`$2\`"; }
have() { command -v "$1" >/dev/null 2>&1; }

echo "# L2 environment (generated by docker/verify.sh)"
echo
echo "Generated: $(date '+%Y-%m-%d %H:%M:%S %Z')"
echo "Repository: $(git rev-parse --short HEAD 2>/dev/null || echo 'no git metadata')"
echo

# ---------------------------------------------------------------- host / docker
echo "## Host"
if have docker; then
  ok "docker" "$(docker --version 2>&1)"
  ok "docker server" "$(docker info --format '{{.OSType}} {{.Architecture}} server {{.ServerVersion}}' 2>&1 | head -1)"
  echo "- docker storage driver / root: \`$(docker info --format '{{.Driver}} {{.DockerRootDir}}' 2>&1 | head -1)\`"
else
  fail "docker" "docker not installed on this machine"
  echo
  echo "> Cannot continue: run this script on a machine that has Docker with Linux containers."
  exit 1
fi
ok "host kernel" "$(uname -srm 2>&1)"
ok "host os" "$( (cat /etc/os-release 2>/dev/null | sed -n 's/^PRETTY_NAME="\(.*\)"/\1/p') || (command -v sw_vers >/dev/null && sw_vers -productVersion) || echo unknown)"
ok "cpu (host)" "$( (nproc 2>/dev/null || sysctl -n hw.ncpu 2>/dev/null || echo unknown) ) logical cores"
echo

# ---------------------------------------------------------------------- builds
build_image() {
  local base="$1" tag="$2" label="$3" log start end
  log="$(mktemp)"
  # Pull explicitly: BuildKit keeps pulled base layers in its cache without
  # registering them as images, so `docker image inspect` on the base tag would
  # report no RepoDigests — and the digest is exactly what we need to pin.
  docker pull "$base" >/dev/null 2>&1 || true
  echo "Building $tag from $base ..." >&2
  start=$(date +%s)
  if docker build --build-arg GO_IMAGE="$base" -t "$tag" . >"$log" 2>&1; then
    end=$(date +%s)
    echo "### $label"
    ok "build" "$tag from $base"
    echo "- build time (cold-ish): **$((end - start)) s**"
    echo "- image size: \`$(docker images "$tag" --format '{{.Size}}')\`"
    local base_digest
    base_digest="$(docker image inspect "$base" --format '{{index .RepoDigests 0}}' 2>/dev/null)"
    if [ -n "$base_digest" ]; then
      echo "- base image digest: \`$base_digest\`"
    else
      echo "- base image digest: **not available** (no RepoDigests; do not pin from this run)"
    fi
    echo
    echo "### $label — inside the container"
    echo '```'
    docker run --rm "$tag" sh -c '
      uname -a
      go version
      go env GOOS GOARCH GOVERSION GOTOOLCHAIN
      echo "GOMAXPROCS=$GOMAXPROCS CGO_ENABLED=$CGO_ENABLED"
      gcc --version | head -1
      head -2 /etc/os-release
    ' 2>&1 | sed 's/^/  /'
    echo '```'
  else
    end=$(date +%s)
    echo "### $label — FAILED after $((end - start)) s"
    echo '```'
    tail -25 "$log"
    echo '```'
  fi
  rm -f "$log"
  echo
}

if [ "$BUILD" = "1" ]; then
  build_image "$BASE22" "$TAG22" "Go 1.22 image (main reproduction)"
  if [ "$MODE" != "quick" ]; then
    build_image "$BASE21" "$TAG21" "Go 1.21 image (Extension control group)"
  fi
else
  echo "### images (build skipped)"
  docker images | grep -E "cs340-repro|REPOSITORY" || echo "(no cs340-repro images)"
  echo
fi

# ------------------------------------------------------------- detector sanity
if docker image inspect "$TAG22" >/dev/null 2>&1; then
  echo "## Detector sanity check (\`-race\` must report a data race)"
  tmp="$(mktemp -d)"
  cat > "$tmp/main.go" <<'GO'
package main

import (
	"fmt"
	"sync"
)

func main() {
	var wg sync.WaitGroup
	x := 0
	for i := 0; i < 4; i++ {
		wg.Add(1)
		go func() { defer wg.Done(); x++ }()
	}
	wg.Wait()
	fmt.Println("x =", x)
}
GO
  out="$(docker run --rm -v "$tmp:/work" -w /work "$TAG22" \
        bash -c 'go mod init probe >/dev/null 2>&1; go run -race main.go 2>&1' 2>&1)"
  if printf '%s' "$out" | grep -q "DATA RACE"; then
    echo "- **PASS** — \`-race\` reported a data race, the detector works in this image"
  else
    echo "- **FAIL** — no DATA RACE in the output; the race detector is not active. Last lines:"
    echo '```'
    printf '%s\n' "$out" | tail -10
    echo '```'
  fi
  rm -rf "$tmp"
  echo
fi

# ------------------------------------------------------------------- summary
echo "## What to do with this block"
echo
echo "1. Paste the sections above into \`docs/environment.md\` (L2 table)."
echo "2. Copy the *base image digest* into the comment block at the top of the \`Dockerfile\`,"
echo "   then pin \`ARG GO_IMAGE=golang@sha256:...\`."
echo "3. Commit with: \`env: record measured L2 environment and pin image digest (1240012291 张歆海)\`"
echo "4. Expected runtimes live in the README: use the build times above."
